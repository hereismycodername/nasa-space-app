//! Regenerate the web figure from the native UI's original vector geometry.
//! Run: rustc scripts/export-anatomy.rs -o /tmp/export-anatomy
//!      /tmp/export-anatomy > src/features/anatomy/anatomyData.ts

#[allow(dead_code)]
#[path = "../ui/crates/ui-model/src/anatomy.rs"]
mod anatomy;

use std::io::{self, Write};

fn main() -> io::Result<()> {
    let mut out = io::BufWriter::new(io::stdout().lock());
    writeln!(out, "// Generated by scripts/export-anatomy.rs from ui-model/src/anatomy.rs.\n// Geometry is prepared at build time; the React view only renders SVG paths.\nimport type {{ AnatomyPart }} from './types'\n\nexport const anatomyParts: AnatomyPart[] = [")?;
    for part in anatomy::parts() {
        let layer = match part.layer {
            anatomy::Layer::Skin => "skin",
            anatomy::Layer::Skeleton => "skeleton",
            anatomy::Layer::Organ => "organ",
        };
        let (points, width, closed) = match &part.geo {
            anatomy::Geo::Fill(points) => (points, 0.0, true),
            anatomy::Geo::Line(points, width) => (points, *width, false),
        };
        write!(out, "  {{ system: '{}', name: '{}', layer: '{}', color: '#{:02x}{:02x}{:02x}', width: {:.2}, hit: {}, d: '", part.sys, part.name, layer, part.tissue[0], part.tissue[1], part.tissue[2], width, part.hit)?;
        for (index, point) in points.iter().enumerate() {
            write!(
                out,
                "{}{:.2},{:.2}",
                if index == 0 { "M" } else { "L" },
                point.x,
                point.y
            )?;
        }
        writeln!(out, "{}' }},", if closed { "Z" } else { "" })?;
    }
    writeln!(out, "]")?;
    out.flush()
}

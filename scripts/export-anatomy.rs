//! Regenerate the web figure from the native UI's original vector geometry.
//! Run: rustc scripts/export-anatomy.rs -o /tmp/export-anatomy
//!      /tmp/export-anatomy > src/features/anatomy/anatomyData.ts

#[allow(dead_code)]
#[path = "../ui/crates/ui-model/src/anatomy.rs"]
mod anatomy;
#[allow(dead_code)]
#[path = "../ui/crates/ui-model/src/anatomy_data.rs"]
mod anatomy_data;

use std::io::{self, Write};

fn main() -> io::Result<()> {
    let mut out = io::BufWriter::new(io::stdout().lock());
    writeln!(out, "// Generated by scripts/export-anatomy.rs from ui-model/src/anatomy.rs.\n// BodyParts3D, (c) The Database Center for Life Science.\n// CC Attribution 4.0 International; source mesh headers: CC BY-SA 2.1 Japan.\n// https://dbarchive.biosciencedbc.jp/en/bodyparts3d/lic.html\n// Frontal projection of a reference model, not a patient-specific scan.\nimport type {{ AnatomyPart, SystemId }} from './types'\n\nexport const ANATOMY_ANCHORS: Record<SystemId, {{ x: number; y: number; labelX: number; labelY: number; side: 'left' | 'right' }}> = {{")?;
    for callout in anatomy::callouts() {
        let (side, label_x) = match callout.side {
            anatomy::Side::Left => ("left", -37),
            anatomy::Side::Right => ("right", 277),
        };
        writeln!(
            out,
            "  {}: {{ x: {:.2}, y: {:.2}, labelX: {}, labelY: {:.2}, side: '{}' }},",
            callout.sys, callout.anchor.x, callout.anchor.y, label_x, callout.label_y, side
        )?;
    }
    writeln!(out, "}}\n\nexport const anatomyParts: AnatomyPart[] = [")?;
    for part in anatomy::parts() {
        let layer = match part.layer {
            anatomy::Layer::Skin => "skin",
            anatomy::Layer::Skeleton => "skeleton",
            anatomy::Layer::Organ => "organ",
        };
        let (points, width, closed) = match &part.geo {
            anatomy::Geo::Fill(points) => (points, 0.0, true),
            anatomy::Geo::Line(points, width) => (points, *width, false),
        };
        write!(out, "  {{ system: '{}', name: '{}', layer: '{}', color: '#{:02x}{:02x}{:02x}', width: {:.2}, hit: {}, d: '", part.sys, part.name, layer, part.tissue[0], part.tissue[1], part.tissue[2], width, part.hit)?;
        for (index, point) in points.iter().enumerate() {
            write!(
                out,
                "{}{:.2},{:.2}",
                if index == 0 { "M" } else { "L" },
                point.x,
                point.y
            )?;
        }
        writeln!(out, "{}' }},", if closed { "Z" } else { "" })?;
    }
    writeln!(out, "]")?;
    out.flush()
}
